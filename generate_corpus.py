def num_word(n):
    ones = ["ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь",
            "восемь", "девять", "десять", "одиннадцать", "двенадцать", "тринадцать",
            "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать",
            "девятнадцать"]
    tens = {2: "двадцать", 3: "тридцать", 4: "сорок", 5: "пятьдесят", 6: "шестьдесят",
            7: "семьдесят", 8: "восемьдесят", 9: "девяносто", 10: "сто"}
    if n < 20:
        return ones[n]
    t, u = divmod(n, 10)
    if u == 0:
        return tens[t]
    return tens[t] + " " + ones[u]

